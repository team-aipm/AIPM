/**
 * 학생 모델에게 줄 입력.
 *
 * 지금까지의 대화와 방금 상대가 한 말을 그대로 준다. 단계 프롬프트가
 * 쓰는 JSON 을 그대로 주면 학생이 내부 상태를 읽어 버린다 —
 * `verified_answer` 를 보고 정답을 말하면 시험이 안 된다.
 */
export function studentInput(
  history: { who: string; text: string }[],
  latest: string,
  choices: string[] = [],
): string {
  const lines = history
    .slice(-12)
    // **이름표에 역할을 넣지 않는다.** "선생님:" 이라고 적어 주면
    // 학생 모델이 상대를 선생님으로 여기고 그렇게 부른다. Persona 를
    // FRIEND 로 골라도 대화에는 선생님이 나온다 — 도구가 페르소나를
    // 덮어쓰는 셈이다. "상대" 는 부르는 말이 아니라 표시일 뿐이다.
    .map((turn) => `${turn.who === 'user' ? '나' : 'AI'}: ${turn.text}`);
  lines.push(`AI: ${latest}`);

  // 보기가 있으면 보여 준다. 화면의 학생은 버튼을 보는데 자동 실행의
  // 학생만 못 보면, 우리가 시험하려는 것과 다른 상황을 시험하게 된다.
  if (choices.length > 0) {
    lines.push('');
    lines.push('고를 수 있는 보기:');
    for (const [index, label] of choices.entries()) {
      lines.push(`${index + 1}. ${label}`);
    }
    // 번호로 답하면 대화 기록에 "1번" 만 남는다. 그 대화를 나중에
    // 읽는 사람도, 다음 턴의 모델도 무슨 뜻인지 알 수 없다.
    lines.push('보기를 고를 때는 번호가 아니라 그 문장을 그대로 말한다.');
  }

  lines.push('나:');
  return lines.join('\n');
}

/**
 * 학생 모델의 답을 다듬는다.
 *
 * 모델이 `나:` 를 다시 붙이거나 따옴표로 감싸는 일이 잦다. 그대로
 * 대화에 넣으면 다음 턴에 그게 또 예시가 되어 굳는다.
 */
export function cleanStudentReply(raw: string): string {
  let text = raw.trim();
  text = text.replace(/^```[a-z]*\n?/i, '').replace(/\n?```$/, '');
  text = text.replace(/^(나|학생)\s*[:：]\s*/, '');
  if (text.length > 1 && text.startsWith('"') && text.endsWith('"')) {
    text = text.slice(1, -1);
  }
  return text.trim();
}

/**
 * 다시 해 볼 만한 오류인가.
 *
 * 503 은 "지금 붐빈다" 는 뜻이지 우리가 뭘 잘못한 게 아니다. 그런데
 * 지금까지는 그걸로 실행 전체가 죽었다. 아홉 회차를 돌리다 여섯 번째에
 * 503 이 나면 앞의 다섯 회차까지 같이 버려졌다.
 *
 * ```text
 * 429  너무 자주 불렀다
 * 500  서버 안에서 터졌다
 * 502  게이트웨이
 * 503  붐빈다
 * 504  시간 초과
 * ```
 *
 * **4xx 중 429 만 재시도한다.** 400(잘못된 요청) · 401(키) · 404(없는
 * 모델) 는 다시 불러도 똑같다. 기다리는 동안 요금만 나가고 원인을
 * 늦게 안다.
 *
 * 오류 글은 `Gemini 503\n{...}` 모양으로 온다. 앞의 숫자를 본다.
 */
export function isTransient(error: string | null): boolean {
  if (error === null) return false;

  const code = /^\D*(\d{3})\b/.exec(error);
  if (code !== null) {
    return ['429', '500', '502', '503', '504'].includes(code[1]);
  }

  // 상태 코드가 안 붙는 것들. 그물을 좁게 친다 — 애매하면 안 기다린다.
  return /timeout|timed out|ECONNRESET|ETIMEDOUT|fetch failed|network/i.test(error);
}

/**
 * 몇 초 기다렸다 다시 부를지.
 *
 * 붐빌 때 바로 다시 부르면 더 붐빈다. 회를 거듭할수록 길게 쉰다.
 * 목록을 넘어가면 마지막 값을 쓴다.
 */
const BACKOFF = [3, 8, 20, 45];

export function waitFor(attempt: number): number {
  return BACKOFF[Math.min(attempt, BACKOFF.length - 1)];
}
