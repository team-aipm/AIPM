export type AutoLimits = {
  /** 상대가 말할 수 있는 총 횟수 */
  students: number;
  /** 단계를 옮길 수 있는 총 횟수 */
  moves: number;
  /** 일시적 오류일 때 다시 부를 횟수 */
  retries: number;
  /**
   * 몇 바퀴 돌지. **시작 단계로 돌아오면 한 바퀴다.**
   *
   * AIPM 에서는 01 → 02/03 → 05 → 01 이 한 문제다. 한 바퀴만 돌면
   * MODE B 를 한 번도 안 지난다. 두 바퀴면 01 이 "이번엔 네가
   * 내볼래?" 를 권할 자리가 생긴다.
   */
  laps: number;
};

/**
 * 기본 상한.
 *
 * **바퀴 수에 맞춰 잡는다.** 한 바퀴에 학생 발화가 6~7 든다 —
 * 01 에서 모드를 고르는 데 1~2, 문제를 푸는 데 5. 바퀴만 늘리고
 * 학생 발화를 그대로 두면 두 번째 문제가 나오기 전에 멈춘다.
 *
 * 호출은 그보다 두 배쯤 든다. 걸음마다 단계와 학생을 한 번씩 부른다.
 */
export const DEFAULT_LIMITS: AutoLimits = {
  students: 20,
  moves: 12,
  retries: 3,
  laps: 3,
};

/**
 * 호출 상한. **화면에서 받지 않고 계산한다.**
 *
 * "최대 발화는 최대 호출에서 단계 호출만 뺀 숫자 아니냐" 는 물음.
 * 맞다 — 겹친다. 그리고 나머지 셋이 이미 루프를 막고 있으므로 호출은
 * **마지막 그물**일 뿐이다. 숫자를 하나 더 받을 이유가 없다.
 *
 * ```text
 * 걸음    발화 + 이동 + 바퀴 + 1        단계를 부르는 횟수의 상한
 * 호출    (걸음 + 발화) × (1 + 재시도)
 * ```
 *
 * 넉넉하게 잡는다. 여기 걸린다면 다른 셋이 먼저 걸렸어야 한다.
 */
export function callCap(limits: AutoLimits): number {
  const steps = limits.students + limits.moves + limits.laps + 1;
  return (steps + limits.students) * (1 + limits.retries);
}

