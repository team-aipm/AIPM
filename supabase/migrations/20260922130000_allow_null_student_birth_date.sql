-- 자녀 계정 생성에서 생년월일을 받지 않는다 (COM-002 §4 개정)
--
-- ## 왜 고치나
--
-- Figma 「메티_서비스」 의 `자녀 계정 생성` 프레임이 **자녀 정보 두 칸 ·
-- 로그인 정보 세 칸** 만 받는다.
--
--   자녀 정보    이름 또는 별명 · 학년
--   로그인 정보  아이디 · 비밀번호 · 비밀번호 확인
--
-- 생년월일 칸이 없다. 지금은 `not null` 이라 디자인대로 만들면 등록이
-- 되지 않는다.
--
-- ## 받지 않는 편이 낫다
--
-- 학년은 따로 받는다. 학습 난이도와 문제 범위를 정하는 것은 **학년** 이고
-- (COM-002 §4 `grade`, DB CHECK 4~6), 생년월일로 하는 일이 없다.
--
-- 아이의 생년월일은 COM-007 이 말하는 아동 개인정보다. **쓰지 않을 값을
-- 받아 두면 지켜야 할 것만 늘어난다.** 받지 않는 것이 가장 확실한 보호다.
--
-- 컬럼은 지우지 않는다. 이미 등록된 아이들의 값이 들어 있다.
--
-- ## 이름과 별명
--
-- 화면은 칸 하나(「이름 또는 별명」)지만 DB 는 `student_name` 과 `nickname`
-- 둘 다 `not null` 이다. 한 값을 양쪽에 넣고 `nickname_source` 를
-- `name_default` 로 남긴다 — 무엇을 기본으로 썼는지 나중에 설명할 수 있어야
-- 한다(COM-002 §4). **스키마는 건드리지 않는다.**

alter table public.student
  alter column birth_date drop not null;

comment on column public.student.birth_date is
  '아이 생년월일. 자녀 계정 생성에서 받지 않는다(2026-09-22). 난이도·문제 범위는 grade 가 정한다. COM-007 상 쓰지 않을 아동 정보는 받지 않는다.';
